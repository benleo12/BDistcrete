"""The paper's mixture of Sherpa and Herwig: each generator's own weights, the predictions mixed.

At theta = (theta_S, theta_H, xi), the paper takes the events to come from Sherpa at theta_S with
probability 1 - xi and from Herwig at theta_H with probability xi, so the mean of any observable O
over all events is

    <O>(theta) = (1 - xi) <O>_S(theta_S) + xi <O>_H(theta_H) .

Each generator's prediction comes from its own weights on the reference events: the MIX17 head at
xi = 0 gives Sherpa's log ratio at theta_S, and at xi = 1 Herwig's at theta_H, and each set of
weights is normalized over the reference events. The fraction of all events in a bin is such a
mean, so a distribution mixes bin by bin in the same way. A mean inside a window, such as the mean
of 1 - T inside the window of the calculation, is each generator's own mean there, mixed with the
same (1 - xi, xi). A calculation is imposed on each generator alone, and the imposed predictions
are then mixed (impose()). A correction that depends on the generator, such as the factor that
takes a prediction to the hadron level of a measurement, multiplies each generator's prediction
before the mixing (the argument factors).

    from gentune import load_head, axes, mixture

    head = load_head('models/MIX17_head.npz')
    A = head.pack(AE, np.float64)                 # the events' a(Phi), converted once
    theta = axes.default('MIX17')                 # both default tunes, xi = 1/2
    w = mixture.weights(head, A, theta)           # {'sherpa': w_S, 'herwig': w_H}, each sums to one
    mixture.mean(w, O, theta)                     # (1 - xi) <O>_S + xi <O>_H
    wc, info = mixture.impose(w, inwin, F, calc)  # the calculation imposed on each generator alone
    mixture.mean(wc, O, theta)
    mixture.mean_and_error(wc, O, theta, imposed=(inwin, F, info))   # and its statistical error

AE is the event side of the reference events (the AE of the deposit, or of a self-test bundle), and
O one value per event, or one column per observable. For a sample of your own, generated by one
generator at the point theta_from (its fraction 0 for Sherpa, 1 for Herwig), pass theta_from and
the weights are those of head.ratio_weights(); its A is trunk.embed() of its features.

A generator whose coefficient is zero, Herwig at xi = 0 or Sherpa at xi = 1, is left out: its
parameters do not enter, and the weights hold the other generator alone. The statistical error and
the learning band of a prediction with the calculation imposed take imposed=(inwin, F, info) of the
impose() that made the weights; without it they are those of the generators alone.

The head's own value at an interior xi, MixtureHead.weights(A, theta), is the geometric
interpolation q_S^(1 - xi) q_H^xi built into the network, which was trained on runs at xi = 0 and 1
only. The paper does not use it: it evaluates the head only at xi = 0 and xi = 1, as this module
does. Pure numpy.
"""
import numpy as np

from .head import MIXTURE_KINDS
from . import maxent

# The two generators of MIX17, and the fraction at which the head is each of them alone.
GENERATORS = ('sherpa', 'herwig')
XI = {'sherpa': 0.0, 'herwig': 1.0}


def fraction(theta):
    """xi, the fraction of Herwig: the last entry of a MIX17 point, or a number itself."""
    x = np.asarray(theta, np.float64)
    xi = float(x) if x.ndim == 0 else float(x.ravel()[-1])
    if not 0.0 <= xi <= 1.0:
        raise ValueError(f'the fraction xi is {xi}, outside [0, 1]')
    return xi


def coefficients(theta):
    """{'sherpa': 1 - xi, 'herwig': xi} for a MIX17 point theta, or for xi itself."""
    xi = fraction(theta)
    return {'sherpa': 1.0 - xi, 'herwig': xi}


def at_fraction(theta, xi):
    """A copy of theta with the fraction set to xi: 0 is Sherpa at theta_S, 1 Herwig at theta_H."""
    t = np.array(theta, np.float64)
    t[..., -1] = xi
    return t


def points(theta):
    """{'sherpa': theta at xi = 0, 'herwig': theta at xi = 1}: where the head is each generator."""
    return {g: at_fraction(theta, XI[g]) for g in GENERATORS}


def _mixture_head(head):
    if getattr(head, 'kind', None) not in MIXTURE_KINDS:
        raise ValueError(f'{getattr(head, "path", "this head")} is a single-generator head, whose '
                         f'weights are head.weights(A, theta); the mixture of the two generators '
                         f'needs MIX17')


def _own_point(head, theta, g, check_box=True):
    """theta at the fraction of generator g. At the fraction 0 or 1 the other generator's
    parameters do not enter the head, so only g's own parameters are checked against the box."""
    t = at_fraction(theta, XI[g])
    if check_box:
        probe = t.copy()
        other = slice(head.nS, head.nS + head.nH) if g == 'sherpa' else slice(0, head.nS)
        probe[..., other] = head.centre[other]
        if not head.in_box(probe):
            raise head._box_error(probe)
    return t


def _source(head, theta_from, check_box=True):
    """The point a sample of your own was generated at, one generator alone, checked."""
    xi = fraction(theta_from)
    if xi not in (0.0, 1.0):
        raise ValueError(f'theta_from has the fraction {xi:g}. It is the point your sample was '
                         f'generated at, by one generator, so its fraction is 0 (Sherpa) or 1 '
                         f'(Herwig). The network at an interior fraction is its own interpolation '
                         f'between the generators, not a sample either of them makes.')
    return _own_point(head, theta_from, 'sherpa' if xi == 0.0 else 'herwig', check_box)


def _used(theta):
    a = coefficients(theta)
    return [g for g in GENERATORS if a[g] != 0.0]


def log_weights(head, A, theta, theta_from=None, check_box=True):
    """{'sherpa': log w_S, 'herwig': log w_H}: each generator's log weights at theta, the head at
    xi = 0 (Sherpa, at theta_S) and at xi = 1 (Herwig, at theta_H), each normalized over the events
    of A, so that sum(exp(log w_g)) = 1. The xi of theta enters only to leave out a generator whose
    coefficient is zero. With theta_from, the point a sample of your own was generated at by one
    generator (fraction 0 or 1), they are the log weights of head.ratio_weights()."""
    _mixture_head(head)
    src = None if theta_from is None else _source(head, theta_from, check_box)
    Ap = head.pack(A, np.float64)                 # once, for both generators (no copy if it is)
    base = None if src is None else head.logit(Ap, src, False)
    out = {}
    for g in _used(theta):
        f = head.logit(Ap, _own_point(head, theta, g, check_box), False)
        if base is not None:
            f = f - base
        f = f/head.T
        out[g] = f - maxent.logsumexp(f)
    return out


def weights(head, A, theta, theta_from=None, check_box=True):
    """{'sherpa': w_S, 'herwig': w_H}: each generator's weights at theta, each summing to one over
    the events of A (the exponential of log_weights())."""
    return {g: np.exp(l) for g, l in log_weights(head, A, theta, theta_from, check_box).items()}


def n_eff(w):
    """{g: 1/sum w_g^2}, the effective sample size of each generator's weights."""
    return {g: float(1.0/np.sum((np.asarray(v, np.float64)/np.sum(v))**2)) for g, v in w.items()}


def combine(parts, theta, factors=None):
    """(1 - xi) parts['sherpa'] + xi parts['herwig'], for numbers, arrays, or dicts or tuples of
    them, such as each generator's (means, histogram).

    factors, {g: number or array, or a dict or tuple of them laid out as the parts}, multiplies
    each generator's part before the mixing, as the paper does with the factors of a measurement's
    hadron-level convention. A generator whose coefficient is zero is left out, and may be missing
    from parts."""
    a = coefficients(theta)
    used = [g for g in GENERATORS if a[g] != 0.0]
    first = parts[used[0]]
    if isinstance(first, dict):
        return {k: combine({g: parts[g][k] for g in used}, theta,
                           None if factors is None else {g: factors[g][k] for g in used})
                for k in first}
    if isinstance(first, (tuple, list)):
        return tuple(combine({g: parts[g][i] for g in used}, theta,
                             None if factors is None else {g: factors[g][i] for g in used})
                     for i in range(len(first)))
    total = 0.0
    for g in used:
        v = np.asarray(parts[g], np.float64)
        if factors is not None:
            v = v*np.asarray(factors[g], np.float64)
        total = total + a[g]*v
    return float(total) if np.ndim(total) == 0 else total


def event_weights(w, theta):
    """(1 - xi) w_S + xi w_H, one weight per event, summing to one. Its weighted mean of any O is
    the mixed mean. A mean inside a window is not: there the paper mixes each generator's own mean
    in the window, mean(w, O, theta, mask=inwin)."""
    return combine({g: np.asarray(v, np.float64)/np.sum(v) for g, v in w.items()}, theta)


def _parts(w, O, theta, mask):
    """Per generator with a non-zero coefficient: (coefficient, its weights normalized over all
    events, its mean of O, over the masked events with mask)."""
    a = coefficients(theta)
    O = np.asarray(O, np.float64)
    X = O.reshape(len(O), -1)
    m = None if mask is None else np.asarray(mask, bool)
    out = {}
    for g in GENERATORS:
        if a[g] == 0.0:
            continue
        if g not in w:
            raise ValueError(f'w holds no weights of {g}, whose coefficient at this xi is {a[g]:g}')
        wg = np.asarray(w[g], np.float64)
        if len(wg) != len(X):
            raise ValueError(f'{len(wg)} weights of {g} for {len(X)} rows of O')
        wall = wg/wg.sum()
        if m is None:
            mg = wall @ X
        else:
            wm = np.where(m, wg, 0.0)
            mg = (wm/wm.sum()) @ X
        out[g] = (a[g], wall, mg)
    return out, X, O.ndim


def _per_generator(imposed, gs):
    """[(inwin, F, info[g]) for g in gs] from imposed = (inwin, F, info) of impose(), or None."""
    if imposed is None:
        return None
    try:
        inwin, F, info = imposed
    except (TypeError, ValueError):
        raise ValueError('imposed is the tuple (inwin, F, info) of the mixture.impose() that made '
                         'the weights') from None
    for g in gs:
        if not isinstance(info, dict) or g not in info:
            raise ValueError(f'the info of imposed holds no solution for {g}: pass the (inwin, F, '
                             f'info) of the mixture.impose() that made the weights')
    return [(inwin, F, info[g]) for g in gs]


def mean(w, O, theta, mask=None):
    """(1 - xi) <O>_S + xi <O>_H for the weights w of weights(), O one value per event or one
    column per observable. With mask, each generator's mean is over the masked events only,
    normalized there, before the mixing: the paper's mean of 1 - T inside the window is
    mean(w, tau, theta, mask=inwin)."""
    parts, X, nd = _parts(w, O, theta, mask)
    m = sum(a*mg for a, _, mg in parts.values())
    return float(m[0]) if nd == 1 else m


def mean_and_error(w, O, theta, mask=None, imposed=None, factors=None):
    """(mean, statistical error) of mean(w, O, theta, mask), as in the paper: the standard deviation
    over resamples of the events, at linear order. Both generators weight the same events, so the
    error is sqrt(sum_i u_i^2) with
    u_i = sum_g a_g w_g,i r_g,i, a_g the coefficients (1 - xi, xi) and r_g,i the per-event term of
    the generator's own mean: O_i - <O>_g, or (O_i - <O>_g) Theta_i / P_g with mask (P_g the
    generator's weight of the masked events).

    imposed   for the weights of impose(), its (inwin, F, info). The paper solves for each
              generator's multipliers again on every resample, so r_g loses its projection on the
              constraint functions, r_g - (F - <F>_g) J_g^-1 Cov_g(F, r_g) with J_g the Newton
              matrix of that generator's solution. Without it, the error is that of weights with
              no calculation, which for imposed weights is not the paper's.
    factors   {g: number or one number per column}, multiplies each generator's mean and its terms
              u before the mixing, as combine(factors=...) does, and as the paper does when it
              compares a prediction with a measurement.

    For xi = 0 or 1 it is the error of bands.mean_and_error of the one generator."""
    parts, X, nd = _parts(w, O, theta, mask)
    gs = list(parts)
    if factors is None:
        m = sum(a*mg for a, _, mg in parts.values())
    else:
        m = np.atleast_1d(combine({g: parts[g][2] for g in gs}, theta, {g: factors[g] for g in gs}))
    imp = _per_generator(imposed, gs)
    from .bands import _stat_error, _response
    resp = None if imp is None else [_response(parts[g][1], i) for g, i in zip(gs, imp)]
    e = _stat_error([parts[g][1] for g in gs], [parts[g][0] for g in gs], [parts[g][2] for g in gs],
                    lambda j0, j1: X[:, j0:j1], X.shape[1], mask, resp,
                    None if factors is None else [factors[g] for g in gs])
    return (float(m[0]), float(e[0])) if nd == 1 else (m, e)


def histogram(b, w, width, theta, over_bins=False, imposed=None, factors=None):
    """(value, statistical error) of every bin of a distribution, mixed: each generator's fraction
    of all events in the bin over its width, then (1 - xi) S + xi H. b is bands.bin_index() of the
    events and width the bin widths. The error is that of mean_and_error() for the per-event value
    (in bin b)/(width of b); imposed and factors (one number per bin, or a number, per generator)
    as there. over_bins=True normalizes each generator over the events in the bins instead, which
    no distribution of the paper does."""
    from .bands import _histogram
    used = _used(theta)
    for g in used:
        if g not in w:
            raise ValueError(f'w holds no weights of {g}, whose coefficient at this xi is not zero')
    a = coefficients(theta)
    return _histogram(b, [w[g] for g in used], [a[g] for g in used], width, over_bins,
                      _per_generator(imposed, used),
                      None if factors is None else [factors[g] for g in used])


def impose(w, inwin, F, calc, which='central', lam0=None, **kw):
    """The calculation imposed on each generator alone, with gentune.maxent.impose.

    w        the weights of weights(), {g: weights}
    inwin    the window of the calculation over the events, and F its functions on the window
             events, as from calc.functions(tau) (gentune.maxent)
    calc     a gentune.maxent.Targets, such as load_targets('targets_thrust_nlo.npz'), or a pair
             (c, Sigma) of window means and their covariance
    which    'central' or the name of a variation of calc
    lam0     {g: starting multipliers}, for example the solution at a nearby point
    kw       passed on to maxent.impose (floor_rel, tol, maxiter)

    Returns (wc, info): wc = {g: imposed weights}, each summing to one, and info = {g: the info
    dict of maxent.impose, which holds the multipliers as 'lam'}. Mix the imposed predictions with
    mean(wc, O, theta); their statistical error is mean_and_error(wc, O, theta,
    imposed=(inwin, F, info))."""
    out, info = {}, {}
    for g, v in w.items():
        with np.errstate(divide='ignore'):
            lw0 = np.log(np.asarray(v, np.float64))
        l0 = None if lam0 is None else lam0.get(g)
        if isinstance(calc, maxent.Targets):
            lw, lam, inf = calc.impose(lw0, inwin, F, which=which, lam0=l0, **kw)
        else:
            c, Sigma = calc
            if which != 'central':
                raise ValueError('which names a variation of a Targets; with (c, Sigma) pass the '
                                 'varied c itself')
            lw, lam, inf = maxent.impose(lw0, inwin, F, c, Sigma, lam0=l0, **kw)
        out[g] = np.exp(lw)
        info[g] = dict(inf, lam=lam)
    return out, info


def xi_moments(lo=0.0, hi=1.0):
    """(E, var) for xi flat on [lo, hi]: E[i, j] = E[a_i a_j] for (a_0, a_1) = (1 - xi, xi), and
    Var(xi). On [0, 1], E = [[1/3, 1/6], [1/6, 1/3]] and Var(xi) = 1/12."""
    m, v = 0.5*(lo + hi), (hi - lo)**2/12
    e2 = v + m*m
    return np.array([[1 - 2*m + e2, m - e2], [m - e2, e2]]), float(v)


def learning_band(head, A, theta, O, wifi_path, mask=None, theta_from=None, xi_prior=(0.0, 1.0),
                  counts=None, check_box=True, imposed=None, factors=None):
    """The learning band of the mixed mean of O at the generator parameters of theta.

    The mean of each generator depends on the same fitted WiFi weights (models/MIX17_wifi.npz), with
    the derivative g_g of head.learning_band(); the mixed mean has the derivative
    (1 - xi) g_S + xi g_H. As the paper does, its variance is averaged over xi flat on xi_prior,

        band^2 = sum_gh E[a_g a_h] g_g C g_h^T ,  E from xi_moments(*xi_prior) ,

    which on [0, 1] is (g_S C g_S + g_H C g_H + g_S C g_H)/3, and needs both generators whatever
    the xi of theta. xi_prior=None takes the band at the xi of theta instead, with a_g its
    coefficients. mask, theta_from and counts are those of head.learning_band(); with mask, each
    generator's mean is over the masked events. O is one value per event, which returns one band,
    or one column per observable, which returns one band each.

    imposed   (inwin, F, info) of the mixture.impose() at this theta: each g_g is then taken
              through the re-solved multipliers of its generator (head.learning_band), the band of
              the paper with the calculation imposed. Without it, the band of the generators alone.
    factors   {g: number or one number per column}, multiplies each g_g, as for mean_and_error()."""
    _mixture_head(head)
    W = np.load(wifi_path)
    head._check_wifi(W, wifi_path)
    if xi_prior is None:
        a = coefficients(theta)
        E = np.outer([a['sherpa'], a['herwig']], [a['sherpa'], a['herwig']])
    else:
        E = xi_moments(*xi_prior)[0]
    gs = [g for i, g in enumerate(GENERATORS) if E[i].any()]
    src = None if theta_from is None else _source(head, theta_from, check_box)
    imp = dict(zip(gs, _per_generator(imposed, gs))) if imposed is not None else {}
    G = {}
    for g in gs:
        G[g] = head._learning_gradient(A, _own_point(head, theta, g, check_box), O, W, mask, src,
                                       False, counts, imp.get(g), wifi_path)
        if factors is not None:
            G[g] = np.asarray(factors[g], np.float64).reshape(-1, 1)*G[g]
    C = np.asarray(W['C'], np.float64)
    var = sum(E[i, j]*np.einsum('ak,kl,al->a', G[g], C, G[h])
              for i, g in enumerate(GENERATORS) for j, h in enumerate(GENERATORS)
              if E[i, j] != 0 and g in G and h in G)
    band = np.sqrt(np.maximum(var, 0.0))
    return float(band[0]) if np.asarray(O).ndim == 1 else band
