#!/usr/bin/env python3
"""Reconstructed producer of output/floor_eval.json (the precision-floor evaluation of
Sec. 5.3): the missing script was reverse-engineered from the file contents, the paper text,
and the sibling evaluation conventions, and validated by regenerating every stored number
exactly (72/72 fields identical after rounding; see output/floor_eval_recon.json).

WHAT IT MEASURES. Whether the percent-level mean-rate offsets seen at validation statistics
are a floor or a fluctuation: the Stage C conditional reweights the cached reference to the
central held-out point (0.120, 0.46, 1.21) and one off-centre point (0.124, 0.55, 1.50), and
the reweighted means are compared against fresh generator runs at two statistics,
  80k : the full original held-out runs 6902 / 6901 (80000 events each),
 800k : the fresh 800k-event runs 6970 / 6971 generated by gen_floor.sh with new seeds.

CONVENTIONS (all fixed by validation against the stored file):
 * weights: f from the exported ensemble (mean of logits), w = softmax(f/T) with the export's
   fitted temperature, exactly as ab_analysis.Cond / eval_valid.py.
 * observables: the six scalars of the ladder; strange fraction recomputed per event with
   r2_ladder.strange_frac and cast to float64 (the eval_valid convention).
 * the 80k reading uses the FULL held run, not the report half (eval_valid convention, not
   the r2_ladder split; the 800k runs are 10x the 80k statistics as the paper states).
 * offset: off_pct = 100*(mean_reweighted - mean_fresh)/mean_fresh.
 * error: se = sqrt( sum(w^2 (v-mu_r)^2)  +  var(fresh)/N_fresh ), the eval_valid variance
   of the weighted mean (NOT the reeval_bins var_w/neff form, which differs in the third
   decimal); err_pct = 100*se/|mean_fresh|; z = (mean_r - mean_f)/se.
 * rounding: off_pct/err_pct to 3 decimals, z to 2 (matches the stored file bit for bit).

Writes --out (default output/floor_eval_recon.json so the archived original is never
touched). After a retrain of the Stage C export, rerun with
    python floor_eval_gen.py --out output/floor_eval.json --force
to refresh the production file consumed by contract_fig.py.
"""
import os, sys, json, argparse
os.environ.setdefault('LADDER_ACT', 'silu')
import numpy as np
import pandas as pd
from ab_analysis import Cond
from r2_ladder import strange_frac

CSV_OBS = ['mult_total', '1_minus_thrust', 'B_total', 'rho_heavy']
OBS = ['mult_total', 'nbaryon', 'strange', '1_minus_thrust', 'B_total', 'rho_heavy']
DATA = 'data_stageC'
# centre = params of held run 6902, off-centre = params of held run 6901 (gen_floor.sh);
# the 800k floor runs 6970/6971 repeat those parameter points with new seeds.
POINTS = {
    'off-centre': dict(theta=(0.124, 0.55, 1.50), runs={'80k': 6901, '800k': 6971}),
    'centre':     dict(theta=(0.120, 0.46, 1.21), runs={'80k': 6902, '800k': 6970}),
}


def load_run(rid):
    d = np.load(f'{DATA}/particles_full_{rid:04d}.npz')
    sh = pd.read_csv(f'{DATA}/shapes_run_{rid:04d}.csv')
    assert len(sh) == len(d['mask']), f'{rid}: csv/npz length mismatch'
    out = {o: sh[o].values for o in CSV_OBS}
    out['nbaryon'] = d['nbaryon'].astype(float)
    out['strange'] = strange_frac(d['particles'], d['mask']).astype(float)
    return out


def mean_offset(vref, w, vtgt):
    """Mean offset of the reweighted reference against the fresh run, with the combined
    statistical error of both means (eval_valid.py convention on the reference side)."""
    mr = float(np.sum(w * vref))
    mt = float(np.mean(vtgt))
    var_r = float(np.sum(w**2 * (vref - mr)**2))          # variance of the weighted mean
    var_t = float(np.var(vtgt) / len(vtgt))
    se = float(np.sqrt(var_r + var_t))
    return (dict(off_pct=round(100.0*(mr-mt)/mt, 3),
                 err_pct=round(100.0*se/abs(mt), 3),
                 z=round((mr-mt)/se, 2)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='output/floor_eval_recon.json')
    ap.add_argument('--force', action='store_true',
                    help='allow overwriting an existing output file')
    args = ap.parse_args()
    if os.path.exists(args.out) and not args.force:
        sys.exit(f'{args.out} exists; pass --force to overwrite')

    cond = Cond('C')
    ref = np.load('output/models/C_ref.npz')
    robs = {o: ref[o].astype(float) for o in OBS}

    out = {}
    for tag, p in POINTS.items():
        f = cond.f_at(np.array(p['theta']))
        w = np.exp((f - f.max())/cond.T); w /= w.sum()
        out[tag] = {}
        for o in OBS:
            out[tag][o] = {}
        for klabel, rid in p['runs'].items():
            run = load_run(rid)
            for o in OBS:
                st = mean_offset(robs[o], w, run[o])
                out[tag][o][klabel] = st
                print(f'{tag:>10} {klabel:>4} {o:>15}: {st["off_pct"]:+7.3f} +- {st["err_pct"]:.3f} %'
                      f'  (z = {st["z"]:+.2f})')
    json.dump(out, open(args.out, 'w'), indent=1)
    print('->', args.out)


if __name__ == '__main__':
    main()
